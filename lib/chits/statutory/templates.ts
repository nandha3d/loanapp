export function normalizeStateCode(raw?: string | null): StatutoryStateCode {
  const up = String(raw ?? '').trim().toUpperCase();
  if (up === 'TN' || up === 'TAMIL NADU' || up === 'TAMILNADU') return 'TN';
  if (up === 'DL' || up === 'DELHI') return 'DL';
  return 'GENERIC';
}

export function resolveStatutoryTemplate(
  stateCodeRaw: string | null | undefined,
  registerType: StatutoryRegisterType,
): StatutoryTemplateMeta {
  const stateCode = normalizeStateCode(stateCodeRaw);
  const st = STATE_NAMES[stateCode];
  const spec = FORM_SPECS[stateCode][registerType];
  return {
    stateCode,
    stateName: st.name,
    statuteTitle: st.statute,
    registerType,
    formCode: spec.formCode,
    title: spec.title,
    subtitle: spec.subtitle,
    signatureBlocks: spec.signatures,
  };
}
