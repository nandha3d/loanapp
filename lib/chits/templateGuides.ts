export function formatLocalizedTemplate(
  template: string,
  params: Record<string, string | number>,
): string {
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (_, key: string) => {
    const val = params[key];
    return val !== undefined && val !== null ? String(val) : `{${key}}`;
  });
}

